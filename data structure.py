# 1. List
print("List")
fruits = ["Apple", "Mango", "Banana"]
print(fruits)
print(fruits[0])

# 2. Tuple
print("Tuple")
numbers = (10, 20, 30)
print(numbers)
print(numbers[1])

# 3. Set
print("Set")
colors = {"Red", "Blue", "Green"}
print(colors)
colors.add("Pink")
print(colors)

# 4. Dictionary
print("Dictionary")
student = {
    "name": "Esha",
    "age": 20,
    "marks": 85
}
print(student)
print(student["name"])