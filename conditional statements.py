 # If
age = 20
if age >= 18:
    print("You are eligible")

# If-else
number = 7
if number % 2 == 0:
    print("Even number")
else:
    print("Odd number")

# If-elif-else
marks = 75
if marks >= 80:
    print("Grade A")
elif marks >= 70:
    print("Grade B")
else:
    print("Grade C")